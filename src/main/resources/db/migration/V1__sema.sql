-- Evrak Takip: temel şema (Oracle 19c+ / 23ai)

CREATE TABLE birim (
    id   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod  VARCHAR2(20)  NOT NULL UNIQUE,
    ad   VARCHAR2(200) NOT NULL
);

CREATE TABLE kullanici (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kullanici_adi  VARCHAR2(100) NOT NULL UNIQUE,
    ad_soyad       VARCHAR2(200) NOT NULL,
    sifre_hash     VARCHAR2(100),
    rol            VARCHAR2(30)  NOT NULL,
    birim_id       NUMBER(19) REFERENCES birim (id)
);

-- Dosya planı: saklama_yili boşsa süresiz saklanır
CREATE TABLE dosya_plani (
    kod          VARCHAR2(20)  PRIMARY KEY,
    ad           VARCHAR2(200) NOT NULL,
    saklama_yili NUMBER(5)
);

-- Yıl ve türe göre sıra numarası sayaçları (satır kilidiyle artırılır)
CREATE TABLE sayac (
    anahtar VARCHAR2(40) PRIMARY KEY,
    deger   NUMBER(19) DEFAULT 0 NOT NULL
);

CREATE TABLE evrak (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kayit_no          VARCHAR2(30) UNIQUE,
    yon               VARCHAR2(10)  NOT NULL,
    konu              VARCHAR2(300) NOT NULL,
    ilgili_kurum      VARCHAR2(200) NOT NULL,
    evrak_tarihi      DATE NOT NULL,
    dis_sayi          VARCHAR2(60),
    gizlilik          VARCHAR2(20)  NOT NULL,
    aciliyet          VARCHAR2(20)  NOT NULL,
    durum             VARCHAR2(20)  NOT NULL,
    birim_id          NUMBER(19) REFERENCES birim (id),
    olusturan_id      NUMBER(19) NOT NULL REFERENCES kullanici (id),
    imzalayan_id      NUMBER(19) REFERENCES kullanici (id),
    imza_zamani       TIMESTAMP,
    red_gerekcesi     VARCHAR2(1000),
    cevap_suresi_sonu DATE,
    ilgili_evrak_id   NUMBER(19) REFERENCES evrak (id),
    cevap_evrak_id    NUMBER(19) REFERENCES evrak (id),
    tamamlama_notu    VARCHAR2(1000),
    dosya_kodu        VARCHAR2(20) REFERENCES dosya_plani (kod),
    arsiv_tarihi      DATE,
    imha_tarihi       DATE,
    kayit_zamani      TIMESTAMP NOT NULL,
    surum             NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT ck_evrak_yon CHECK (yon IN ('GELEN', 'GIDEN')),
    CONSTRAINT ck_evrak_gizlilik CHECK (gizlilik IN ('NORMAL', 'HIZMETE_OZEL', 'GIZLI')),
    CONSTRAINT ck_evrak_aciliyet CHECK (aciliyet IN ('NORMAL', 'ACELE', 'GUNLUDUR')),
    CONSTRAINT ck_evrak_durum CHECK (durum IN ('TASLAK', 'IMZA_BEKLIYOR', 'KAYITLI', 'HAVALEDE', 'TAMAMLANDI', 'ARSIVLENDI'))
);

CREATE INDEX ix_evrak_birim ON evrak (birim_id);
CREATE INDEX ix_evrak_durum ON evrak (durum);
CREATE INDEX ix_evrak_cevap_suresi ON evrak (cevap_suresi_sonu);

CREATE TABLE sevk (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evrak_id          NUMBER(19) NOT NULL REFERENCES evrak (id),
    sevk_eden_id      NUMBER(19) NOT NULL REFERENCES kullanici (id),
    hedef_birim_id    NUMBER(19) NOT NULL REFERENCES birim (id),
    hedef_kullanici_id NUMBER(19) REFERENCES kullanici (id),
    talimat           VARCHAR2(500),
    durum             VARCHAR2(20) NOT NULL,
    sevk_zamani       TIMESTAMP NOT NULL,
    alinma_zamani     TIMESTAMP
);

CREATE INDEX ix_sevk_evrak ON sevk (evrak_id);
CREATE INDEX ix_sevk_hedef_kullanici ON sevk (hedef_kullanici_id);

CREATE TABLE bilgi_edinme (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    basvuru_no          VARCHAR2(30)  NOT NULL UNIQUE,
    basvuran_ad         VARCHAR2(200) NOT NULL,
    tc_maskeli          VARCHAR2(11),
    iletisim            VARCHAR2(300),
    kanal               VARCHAR2(20)  NOT NULL,
    konu                VARCHAR2(1000) NOT NULL,
    basvuru_tarihi      DATE NOT NULL,
    durum               VARCHAR2(20)  NOT NULL,
    birim_id            NUMBER(19) REFERENCES birim (id),
    birim_gorusu        VARCHAR2(1000),
    sure_sonu           DATE NOT NULL,
    uzatma_sayisi       NUMBER(10) DEFAULT 0 NOT NULL,
    uzatma_gerekcesi    VARCHAR2(1000),
    sonuc_metni         VARCHAR2(2000),
    ret_nedeni          VARCHAR2(40),
    sonuc_tarihi        DATE,
    itiraz_son_tarihi   DATE,
    yonlendirilen_kurum VARCHAR2(200),
    olusturan_id        NUMBER(19) NOT NULL REFERENCES kullanici (id),
    kayit_zamani        TIMESTAMP NOT NULL,
    surum               NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT ck_be_durum CHECK (durum IN ('ALINDI', 'INCELEMEDE', 'CEVAPLANDI', 'REDDEDILDI', 'YONLENDIRILDI')),
    CONSTRAINT ck_be_uzatma CHECK (uzatma_sayisi BETWEEN 0 AND 1)
);

CREATE INDEX ix_be_durum ON bilgi_edinme (durum);
CREATE INDEX ix_be_birim ON bilgi_edinme (birim_id);
CREATE INDEX ix_be_sure_sonu ON bilgi_edinme (sure_sonu);

CREATE TABLE resmi_tatil (
    tarih DATE PRIMARY KEY,
    ad    VARCHAR2(100) NOT NULL
);

CREATE TABLE denetim_kaydi (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zaman         TIMESTAMP NOT NULL,
    kullanici_adi VARCHAR2(100) NOT NULL,
    islem         VARCHAR2(50)  NOT NULL,
    varlik_turu   VARCHAR2(30)  NOT NULL,
    varlik_id     NUMBER(19),
    ayrinti       VARCHAR2(2000)
);

CREATE INDEX ix_denetim_varlik ON denetim_kaydi (varlik_turu, varlik_id);
